/** A clean spec, or null. Unknown ids, duplicates and a fourth filter are dropped; ranges are clamped and ordered. */
export function cleanSpec(input) {
  if (!input || typeof input !== 'object') return null;
  const market = input.market === 'total' ? 'total' : input.market === 'spread' ? 'spread' : null;
  if (!market) return null;
  const side = SIDES[market].some(s => s.value === input.side) ? input.side : SIDES[market][0].value;
  const filters = [], seen = new Set();
  for (const raw of Array.isArray(input.filters) ? input.filters : []) {
    if (filters.length >= MAX_FILTERS) break;
    const c = conditionOf(raw?.id);
    if (!c || c.hidden || seen.has(c.id)) continue;
    if (c.kind === 'range') {
      let lo = finite(raw.min) ? raw.min : c.min, hi = finite(raw.max) ? raw.max : c.max;
      lo = Math.min(c.max, Math.max(c.min, c.step === 1 ? Math.round(lo) : half(lo)));
      hi = Math.min(c.max, Math.max(c.min, c.step === 1 ? Math.round(hi) : half(hi)));
      if (lo > hi) [lo, hi] = [hi, lo];
      filters.push({ id: c.id, min: lo, max: hi });
    } else if (c.kind === 'team') {
      const who = WHO[market].some(w => w.value === raw.who) ? raw.who : 'either';
      filters.push({ id: c.id, who });
    } else filters.push({ id: c.id });
    seen.add(c.id);
  }
  return { market, side, filters };
}
export const specKey = spec => JSON.stringify(cleanSpec(spec));

const fmtNum = x => (Number.isInteger(x) ? String(x) : x.toFixed(1));
const sideLabel = spec => SIDES[spec.market].find(s => s.value === spec.side)?.label ?? spec.side;
function whoLabel(market, who) {
  const w = WHO[market].find(x => x.value === who);
  return w ? w.label : 'Either team';
}
/** One filter in words: "Divisional game", "Backed team off a bye (13+ days of rest)", "Total 41 to 47.5". */
export function filterText(spec, f) {
  const c = conditionOf(f.id);
  if (!c) return '';
  if (c.kind === 'team') return `${whoLabel(spec.market, f.who)} ${c.phrase}`;
  if (c.kind === 'range') {
    const top = f.max === c.max;
    if (c.id === 'seasons') return top ? `Seasons ${f.min} on` : f.min === f.max ? `Season ${f.min}` : `Seasons ${f.min}–${f.max}`;
    const name = c.id === 'spread' ? 'Favorite by' : 'Total';
    return top ? `${name} ${fmtNum(f.min)} or more` : `${name} ${fmtNum(f.min)} to ${fmtNum(f.max)}`;
  }
  return c.label;
}
/** The trend in words: "Spread · Underdog · Divisional game · Backed team off a bye (13+ days of rest)". */
export function specTitle(spec) {
  const s = cleanSpec(spec);
  if (!s) return '';
  return [s.market === 'spread' ? 'Spread' : 'Total', sideLabel(s), ...s.filters.map(f => filterText(s, f))].join(' · ');
}
/** Which markets' lines a spec needs to be checked on an upcoming game. */
export function specNeeds(spec) {
  const s = cleanSpec(spec);
  const needs = new Set();
  if (!s) return needs;
  if (s.market === 'spread' && ['fav', 'dog'].includes(s.side)) needs.add('spread');
  for (const f of s.filters) { const n = conditionOf(f.id)?.needs; if (n === 'spread' || n === 'total') needs.add(n); }
  return needs;
}

