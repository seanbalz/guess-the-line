const GRASS = new Set(['grass', 'dessograss']);
/**
 * Condition values for one upcoming game of the week file (`shared/trends/<season>-week-NN.json` `games[]`), using the
 * same definitions as shared/trends.mjs buildFeatures (tests/trend-builder.test.mjs checks them against the engine).
 * Returns `{ game: Map(id → true|false|null), team: [Map, Map] }` with team index 0 home, 1 away.
 */
export function weekGameConditions(entry, week) {
  const f = entry?.flags ?? {};
  const reg = Number.isInteger(week) && week <= 18;
  const known = typeof f.window === 'string';
  const roof = f.roof === 'dome' || f.roof === 'closed' ? 'in' : f.roof === 'outdoors' || f.roof === 'open' ? 'out' : null;
  const rest = [f.rest?.[entry.home] ?? null, f.rest?.[entry.away] ?? null];
  const game = new Map([
    ['div', f.divisional === true], ['nondiv', f.divisional !== true],
    ['confNondiv', f.divisional !== true && f.interconference === false], ['interconf', f.interconference === true],
    ['prime', known ? f.window === 'primetime' : null], ['early', known ? f.window === 'early' : null], ['late', known ? f.window === 'late' : null],
    ['thu', f.day === 'TNF' && reg], ['snf', f.day === 'SNF'], ['mnf', f.day === 'MNF'],
    ['w1_4', reg && week <= 4], ['w5_8', reg && week >= 5 && week <= 8], ['w9_12', reg && week >= 9 && week <= 12], ['w13p', reg && week >= 13], ['post', !reg],
    ['indoor', roof === null ? null : roof === 'in'], ['outdoor', roof === null ? null : roof === 'out'],
    ['grass', f.surface ? GRASS.has(f.surface) : false], ['turf', f.surface ? !GRASS.has(f.surface) : false],
    ['bothBye', rest.every(r => finite(r) && r >= 13) && reg], ['bothShort', rest.every(r => finite(r) && r <= 5)],
    ['wind10', null], ['wind15', null], ['cold', null], ['neutral', f.neutral === true],
  ]);
  const travel = side => (Array.isArray(f.travel) ? f.travel.find(t => t.team === (side === 0 ? entry.home : entry.away)) : null);
  const team = [0, 1].map(side => {
    const r = rest[side], o = rest[1 - side];
    return new Map([
      ['bye', finite(r) && r >= 13 && reg], ['short', finite(r) && r <= 5], ['restAdv', finite(r) && finite(o) && r - o >= 3],
      ['traveling', travel(side)?.traveling === true],
    ]);
  });
  return { game, team };
}

/**
 * One upcoming game against a spec: `{ state, side }`. `state` is 'match', 'no', 'locked' (a line condition or the
 * favorite needs a market this viewer has not opened: no value is read), or 'unknown' (observed weather, an unknown
 * roof, or no saved line of the viewer's own). `lines` is the viewer's own saved line per market in nflverse convention
 * (positive when the home team is favored), only for markets `access` opens; anything else is ignored.
 */
export function matchGame(input, { entry, week, access = {}, lines = {} }) {
  const spec = cleanSpec(input);
  if (!spec || !entry) return { state: 'no', side: null };
  const values = weekGameConditions(entry, week);
  const line = market => (access?.[market] === true && finite(lines?.[market]) ? lines[market] : null);
  let pending = null; // 'locked' outranks 'unknown': both mean "cannot say yet"
  const hold = state => { if (pending !== 'locked') pending = state; };
  // Non-line conditions first, so a game that fails them never shows as waiting on a line.
  let backed = spec.market === 'spread' ? (spec.side === 'home' ? 0 : spec.side === 'away' ? 1 : null) : null;
  if (spec.market === 'spread' && backed === null) {
    if (access?.spread !== true) hold('locked');
    else if (line('spread') === null) hold('unknown');
    else if (line('spread') === 0) return { state: 'no', side: null };
    else { const favorite = line('spread') > 0 ? 0 : 1; backed = spec.side === 'fav' ? favorite : 1 - favorite; }
  }
  if (spec.market === 'spread' && ['home', 'away'].includes(spec.side) && values.game.get('neutral') === true) return { state: 'no', side: null };
  for (const f of spec.filters) {
    const c = conditionOf(f.id);
    if (c.kind === 'game') {
      const v = values.game.get(c.id);
      if (v === false) return { state: 'no', side: null };
      if (v === null || v === undefined) hold('unknown');
    } else if (c.kind === 'team') {
      const at = side => values.team[side].get(c.id) ?? null;
      let v;
      if (f.who === 'home') v = at(0);
      else if (f.who === 'away') v = at(1);
      else if (f.who === 'either') v = at(0) === true || at(1) === true ? true : at(0) === null || at(1) === null ? null : false;
      else if (backed === null) { v = undefined; } // decided once the favorite is known
      else v = at(f.who === 'pick' ? backed : 1 - backed);
      if (v === false) return { state: 'no', side: null };
      if (v === null) hold('unknown');
    } else if (c.id === 'seasons') {
      const season = finite(entry.season) ? entry.season : SEASON_OF(entry);
      if (!inSeasons(f, season)) return { state: 'no', side: null };
    }
  }
  for (const f of spec.filters) {
    const c = conditionOf(f.id);
    if (c.kind !== 'range' || c.id === 'seasons') continue;
    if (access?.[c.needs] !== true) { hold('locked'); continue; }
    const x = line(c.needs);
    if (x === null) { hold('unknown'); continue; }
    if (!inRange(f, c.id === 'spread' ? Math.abs(x) : x)) return { state: 'no', side: null };
  }
  if (pending) return { state: pending, side: null };
  if (spec.market === 'total') return { state: 'match', side: spec.side };
  return { state: 'match', side: backed === 0 ? entry.home : entry.away };
}
const SEASON_OF = entry => Number(String(entry?.nflverseId ?? '').slice(0, 4)) || null;

/**
 * Every game of the week against a spec, in the week's order. `games` are `{ id, entry, access, lines, started }`.
 * Counts only upcoming games as matches this week.
 */
export function weekMatches(spec, { games = [], week }) {
  const rows = games.map(g => ({ id: g.id, title: g.title ?? g.id, started: g.started === true, ...matchGame(spec, { entry: { ...g.entry, season: g.season ?? SEASON_OF(g.entry) }, week, access: g.access, lines: g.lines }) }));
  const upcoming = rows.filter(r => !r.started);
  return { rows, matches: upcoming.filter(r => r.state === 'match').length, waiting: upcoming.filter(r => r.state === 'locked').length };
}

// ---------------------------------------------------------------------------
// Saved trends: this device only (localStorage, every access wrapped). Kept in the order saved; never ranked.
// ---------------------------------------------------------------------------
const storageOf = storage => {
  try { return storage ?? globalThis.localStorage ?? null; } catch { return null; }
};
export function readSaved(storage) {
  const s = storageOf(storage);
  if (!s) return [];
  let parsed;
  try { parsed = JSON.parse(s.getItem(SAVED_KEY) ?? 'null'); } catch { return []; }
  const items = Array.isArray(parsed?.items) ? parsed.items : [];
  const out = [], keys = new Set();
  for (const item of items) {
    const spec = cleanSpec(item?.spec);
    if (!spec || typeof item.id !== 'string' || !/^[\w-]{1,40}$/.test(item.id)) continue;
    const key = specKey(spec);
    if (keys.has(key)) continue;
    keys.add(key);
    out.push({ id: item.id, spec, savedAt: typeof item.savedAt === 'string' ? item.savedAt.slice(0, 40) : null });
    if (out.length >= MAX_SAVED) break;
  }
  return out;
}
function write(items, storage) {
  const s = storageOf(storage);
  if (!s) return false;
  try { s.setItem(SAVED_KEY, JSON.stringify({ v: 1, items })); return true; } catch { return false; }
}
/** Save a spec (a duplicate is not added again). Returns `{ ok, items, item }`; `ok` is false when storage refused. */
export function saveTrend(input, { storage, now = new Date().toISOString(), id } = {}) {
  const spec = cleanSpec(input);
  const items = readSaved(storage);
  if (!spec) return { ok: false, items, item: null };
  const existing = items.find(i => specKey(i.spec) === specKey(spec));
  if (existing) return { ok: true, items, item: existing };
  if (items.length >= MAX_SAVED) return { ok: false, items, item: null, full: true };
  const item = { id: id ?? `t${Date.parse(now).toString(36)}${Math.floor(Math.random() * 1296).toString(36)}`, spec, savedAt: now };
  const next = [...items, item];
  return write(next, storage) ? { ok: true, items: next, item } : { ok: false, items, item: null };
}
export function removeTrend(id, { storage } = {}) {
  const items = readSaved(storage).filter(i => i.id !== id);
  return { ok: write(items, storage), items };
}

