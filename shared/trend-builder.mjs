// Trend builder (proposed D-62): a member stacks up to three conditions on one market and side and sees how that
// situation went against the nflverse closing line. Pure and browser-safe: no React, no storage, no clock.
//
// Honesty rules (docs/TRENDS.md "Trend builder"): a built trend is always labelled "Found by search — not tested";
// it is never ranked or sorted by win rate, units or ROI; modelled returns are "Illustrative units at -110"; the
// 2002–2017 / 2018+ split is shown as a check the builder could see, not as an out-of-sample test. Every condition is
// one the prepared history already computes (shared/trends.mjs atoms); unknown inputs never count as a match.
//
// The history file (shared/trends/builder-history.json) is generated by scripts/prepare-trend-builder.mjs from the
// frozen nflverse history and the redacted season file. It carries played games only: no current line, no pick.

