/**
 * The decoded history: one row per played game, `{ i, date, season, week, home, away, hs, as, spread, total, g, gk,
 * t: [home, away], tk: [home, away] }`. `spread` is nflverse's (positive when the home team is favored); `g`/`gk` are
 * the game condition values and which of them are known; `t`/`tk` the same per team.
 */
export function decodeHistory(file) {
  if (!file || file.schema !== BUILDER_SCHEMA || !file.games || !Array.isArray(file.teams)) throw new Error('Trend builder history is unavailable.');
  const c = file.games, n = c.season.length, rows = new Array(n);
  const epoch = Date.UTC(SPLIT.builtOnFirst, 0, 1);
  for (let i = 0; i < n; i++) {
    rows[i] = {
      i, date: new Date(epoch + c.day[i] * 86400000).toISOString().slice(0, 10), season: c.season[i], week: c.week[i],
      home: file.teams[c.home[i]], away: file.teams[c.away[i]], hs: c.hs[i], as: c.as[i],
      spread: c.spread[i] / 2, total: c.total[i] / 2, g: c.g[i], gk: c.gk[i],
      t: [c.t[i] & 0xff, (c.t[i] >> 8) & 0xff], tk: [(c.t[i] >> 16) & 0xff, (c.t[i] >> 24) & 0xff],
    };
  }
  return { rows, meta: { version: file.version, source: file.source, coverage: file.coverage } };
}

/** A range's top value means "and above" (seasons: "and later"), so a saved trend keeps working next season. */
const openTop = f => f.max === conditionOf(f.id)?.max;
const inRange = (f, x) => finite(x) && x >= f.min && (openTop(f) || x <= f.max);
const inSeasons = (f, season) => finite(season) && inRange(f, season);
const bitValue = (value, known, bit) => (((known >> bit) & 1) ? Boolean((value >> bit) & 1) : null);
/** For a spread side, the team row it backs: 0 home, 1 away, or null (no favorite, or a neutral site for home/road). */
function backedSide(spec, row) {
  if (spec.market !== 'spread') return null;
  if (spec.side === 'home') return 0;
  if (spec.side === 'away') return 1;
  if (row.spread === 0) return null;
  const favorite = row.spread > 0 ? 0 : 1;
  return spec.side === 'fav' ? favorite : 1 - favorite;
}
/** One team condition on a row: true, false or null (unknown). */
function teamValue(row, c, who, backed) {
  const at = side => bitValue(row.t[side], row.tk[side], c.bit);
  if (who === 'home') return at(0);
  if (who === 'away') return at(1);
  if (who === 'pick' || who === 'opp') {
    if (backed === null) return null;
    return at(who === 'pick' ? backed : 1 - backed);
  }
  const a = at(0), b = at(1);
  if (a === true || b === true) return true;
  return a === null || b === null ? null : false;
}
/** Does a historical row fit the spec: true, false, or null when a chosen condition is unknown there. */
export function rowFits(spec, row) {
  if (spec.market === 'spread' && ['home', 'away'].includes(spec.side) && bitValue(row.g, row.gk, conditionOf('neutral').bit) === true) return false;
  const backed = backedSide(spec, row);
  if (spec.market === 'spread' && backed === null) return false;
  let unknown = false;
  for (const f of spec.filters) {
    const c = conditionOf(f.id);
    let v;
    if (c.kind === 'game') v = bitValue(row.g, row.gk, c.bit);
    else if (c.kind === 'team') v = teamValue(row, c, f.who, backed);
    else {
      v = c.id === 'seasons' ? inSeasons(f, row.season) : inRange(f, c.id === 'spread' ? Math.abs(row.spread) : row.total);
    }
    if (v === false) return false;
    if (v === null) unknown = true;
  }
  return unknown ? null : true;
}
/** The backed side's result on a row: 1 win, -1 loss, 0 push. */
export function rowResult(spec, row) {
  if (spec.market === 'total') {
    const d = row.hs + row.as - row.total;
    const over = Math.sign(d);
    return spec.side === 'over' ? over : -over;
  }
  const homeCover = Math.sign(row.hs - row.as - row.spread);
  return backedSide(spec, row) === 0 ? homeCover : -homeCover;
}

export function wilson(w, n, z = Z95) {
  if (!n) return null;
  const p = w / n, z2 = z * z;
  const centre = (p + z2 / (2 * n)) / (1 + z2 / n);
  const halfWidth = (z * Math.sqrt((p * (1 - p)) / n + z2 / (4 * n * n))) / (1 + z2 / n);
  const r4 = x => Math.round(x * 10000) / 10000;
  return [r4(centre - halfWidth), r4(centre + halfWidth)];
}
const units = (W, L) => Math.round((W * W110 - L) * 10000) / 10000;
function tally(games) {
  let W = 0, L = 0, P = 0;
  for (const g of games) { if (g.result > 0) W++; else if (g.result < 0) L++; else P++; }
  const decided = W + L;
  return { W, L, P, n: games.length, decided, coverRate: decided ? W / decided : null, wilson95: wilson(W, decided), units: units(W, L),
    from: games[0]?.date ?? null, to: games.at(-1)?.date ?? null };
}
/** Same direction, opposite direction, or not comparable. A rate of exactly 50% has no direction. */
export function splitLabel(builtOn, holdOut) {
  if (!builtOn.n || !holdOut.n) return { state: 'empty', text: BUILDER_COPY.splitEmpty };
  if (builtOn.decided < SPLIT_MIN_DECIDED || holdOut.decided < SPLIT_MIN_DECIDED) return { state: 'few', text: BUILDER_COPY.splitFew };
  const dir = r => Math.sign(r.coverRate - 0.5);
  if (dir(builtOn) === 0 || dir(holdOut) === 0) return { state: 'even', text: BUILDER_COPY.splitEven };
  if (dir(builtOn) !== dir(holdOut)) return { state: 'opposite', text: BUILDER_COPY.splitOpposite };
  return { state: 'same', text: BUILDER_COPY.splitSame };
}

/**
 * Evaluate a spec over the decoded history. Games are in date order; nothing is sorted by result. Returns the record,
 * the per-season rows, the cumulative illustrative units series, the period split and the contributing games.
 */
export function evaluateSpec(history, input) {
  const spec = cleanSpec(input);
  if (!spec || !history?.rows) return null;
  const games = [];
  let unknown = 0, missingLine = 0;
  for (const row of history.rows) {
    const line = spec.market === 'spread' ? row.spread : row.total;
    if (!finite(line)) { missingLine++; continue; }
    const fit = rowFits(spec, row);
    if (fit === null) { unknown++; continue; }
    if (!fit) continue;
    games.push({ i: row.i, date: row.date, season: row.season, week: row.week, home: row.home, away: row.away, hs: row.hs, as: row.as,
      spread: row.spread, total: row.total, backed: backedSide(spec, row), result: rowResult(spec, row) });
  }
  const record = tally(games);
  const seasons = [];
  for (const g of games) {
    if (seasons.at(-1)?.season !== g.season) seasons.push({ season: g.season, games: [] });
    seasons.at(-1).games.push(g);
  }
  let running = 0;
  const series = seasons.map(s => { const r = tally(s.games); running = Math.round((running + r.units) * 10000) / 10000; return { season: s.season, ...r, games: undefined, illustrativeUnits: running }; });
  const builtOn = tally(games.filter(g => g.season <= SPLIT.builtOnLast));
  const holdOut = tally(games.filter(g => g.season >= SPLIT.holdOutFirst));
  return { spec, record, series, split: { builtOn, holdOut, ...splitLabel(builtOn, holdOut) }, games, excluded: { unknown, missingLine }, label: BUILDER_COPY.label };
}

