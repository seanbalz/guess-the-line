export const fmtRecord = r => `${r.W}-${r.L}-${r.P}`;
export const fmtPct = x => (finite(x) ? `${(x * 100).toFixed(1)}%` : '—');
export const fmtUnits = x => (!finite(x) ? '—' : Math.abs(x) < 0.005 ? '0.00' : `${x > 0 ? '+' : MINUS}${Math.abs(x).toFixed(2)}`);
export const fmtInterval = w => (w ? `${(w[0] * 100).toFixed(1)}%–${(w[1] * 100).toFixed(1)}%` : '—');
/** A historical game's line in words: "KC −3.5" (spread, the home team's line) or "47.5" (total). */
export function lineText(market, g) {
  if (market === 'total') return fmtNum(g.total);
  if (g.spread === 0) return 'Pick’em';
  const fav = g.spread > 0 ? g.home : g.away;
  return `${fav} ${MINUS}${fmtNum(Math.abs(g.spread))}`;
}
