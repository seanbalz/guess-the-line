#!/usr/bin/env node
// Reproducible, free, public fantasy snapshot; never reads GTL picks or account data.
import { writeFile, mkdir, readdir, rename } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildFantasySnapshot } from '../shared/fantasy-build.mjs';
import { readFantasySources } from './fantasy-sources.mjs';
import { buildRankings } from '../shared/fantasy-rankings.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2), value = flag => args[args.indexOf(flag) + 1];
if (args.includes('--help') || !args.includes('--season') || !args.includes('--week')) {
  console.log('node scripts/fantasy.mjs --season 2026 --week 6 [--input-dir .local/fantasy-sources] [--check]');
  process.exit(args.includes('--help') ? 0 : 1);
}
const season = Number(value('--season')), week = Number(value('--week'));
if (!Number.isInteger(season) || season < 2020 || season > 2200 || !Number.isInteger(week) || week < 2 || week > 18) throw new Error('Provide a valid season and week 2–18. Week 1 has no same-season pace data.');
const { rows, sources } = await readFantasySources({ season, inputDir: args.includes('--input-dir') ? value('--input-dir') : null, root });
const snapshot = buildFantasySnapshot({ season, week, ...rows, sources, generatedAt: new Date().toISOString() });
const rankings = buildRankings(snapshot);
if (rankings.error || !rankings.rows.length) throw new Error('No verified rankings could be generated.');
if (!args.includes('--check')) {
  const directory = path.join(root, 'shared/fantasy');
  await mkdir(directory, { recursive: true });
  const filename = `${season}-week-${String(week).padStart(2, '0')}.json`;
  const target = path.join(directory, filename);
  await writeFile(`${target}.tmp`, JSON.stringify(snapshot) + '\n');
  await rename(`${target}.tmp`, target);
  const files = (await readdir(directory)).filter(name => /^\d{4}-week-\d{2}\.json$/.test(name)).sort();
  const entries = files.map(name => `  '${name.replace('-week-', '-').replace('.json', '')}': () => import('../../shared/fantasy/${name}'),`);
  const latest = files.at(-1).match(/(\d{4})-week-(\d{2})/);
  await writeFile(path.join(root, 'web/src/fantasyWeeks.generated.js'), `// Generated by scripts/fantasy.mjs. Public player statistics only.\nexport const FANTASY_WEEKS = {\n${entries.join('\n')}\n};\nexport const FANTASY_DEFAULT = { season: ${Number(latest[1])}, week: ${Number(latest[2])} };\n`);
}
console.log(JSON.stringify({ season, week, statsThroughWeek: snapshot.statsThroughWeek, players: snapshot.players.length, ranked: rankings.rows.length, withTrends: rankings.rows.filter(row => row.trendHighlights.length).length, byes: rankings.summary.byes, unavailable: rankings.summary.unavailable, written: !args.includes('--check') }));
