// Deterministic server-only public seed. Run with --check to verify without writing.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { parseCsvRows, writeCompactCsv } from '../shared/trends.mjs';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const sha = text => createHash('sha256').update(text).digest('hex');
const historyCsv = read('shared/trends/history-1999-2025.csv');
const frozenSeason = read('shared/trends/season-2026.csv');
const seasonCsv = writeCompactCsv(parseCsvRows(frozenSeason).rows, { redactUnplayed: true });
const registryText = read('shared/trends-registry.json');
const sourceAsOf = /retrieved (\d{4}-\d{2}-\d{2})/.exec(frozenSeason)?.[1];
if (!sourceAsOf) throw new Error('Seed source date is missing.');
const seed = { historyCsv, seasonCsv, season: 2026, sourceAsOf, registry: JSON.parse(registryText),
 venues: JSON.parse(read('shared/nfl-venues.json')), corrections: JSON.parse(read('shared/trends-corrections.json')),
 sources: { history: { file: 'shared/trends/history-1999-2025.csv', sha256: sha(historyCsv) },
 season: { file: 'shared/trends/season-2026.csv', sha256: sha(frozenSeason) }, registrySha256: sha(registryText) } };
const text = '// Generated by scripts/trends-seed.mjs. Server only; public historical evidence and redacted season schedule.\nexport default ' + JSON.stringify(seed) + ';\n';
const path = new URL('../cloud/trends-seed.mjs', import.meta.url);
if (process.argv.includes('--check')) {
 if (readFileSync(path, 'utf8') !== text) throw new Error('Trends seed is out of date.');
 console.log('Trends seed verified (' + Buffer.byteLength(text) + ' bytes).');
} else { writeFileSync(path, text); console.log('Trends seed generated (' + Buffer.byteLength(text) + ' bytes).'); }
