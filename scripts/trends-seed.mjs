// Deterministic server-only public seed. Run with --check to verify without writing.
// The frozen history is shipped as its prepared evaluation state (shared/trends.mjs prepareHistory),
// so a hosted /trends/week request processes only the current season within the Edge CPU limit.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { deflateRawSync, inflateRawSync } from 'node:zlib';
import { pathToFileURL } from 'node:url';
import { parseCsvRows, writeCompactCsv, prepareHistory } from '../shared/trends.mjs';

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const sha = text => createHash('sha256').update(text).digest('hex');
const HEADER = '// Generated by scripts/trends-seed.mjs. Server only; public historical evidence (prepared, raw-deflate base64 JSON) and redacted season schedule.\n';
export const SEED_PATH = new URL('../cloud/trends-seed.mjs', import.meta.url);

/** The seed fields and the prepared-history JSON text, from the committed frozen files. */
export function buildSeed() {
  const historyCsv = read('shared/trends/history-1999-2025.csv');
  const frozenSeason = read('shared/trends/season-2026.csv');
  const seasonCsv = writeCompactCsv(parseCsvRows(frozenSeason).rows, { redactUnplayed: true });
  const registryText = read('shared/trends-registry.json');
  const sourceAsOf = /retrieved (\d{4}-\d{2}-\d{2})/.exec(frozenSeason)?.[1];
  if (!sourceAsOf) throw new Error('Seed source date is missing.');
  const registry = JSON.parse(registryText), venues = JSON.parse(read('shared/nfl-venues.json'));
  const corrections = JSON.parse(read('shared/trends-corrections.json'));
  const registrySha256 = sha(registryText);
  const seed = { seasonCsv, season: 2026, sourceAsOf, registry, venues, corrections,
    sources: { history: { file: 'shared/trends/history-1999-2025.csv', sha256: sha(historyCsv) },
      season: { file: 'shared/trends/season-2026.csv', sha256: sha(frozenSeason) }, registrySha256 } };
  const historyJson = JSON.stringify(prepareHistory({ historyCsv, registry, venues, corrections, season: seed.season, registrySha256 }));
  return { seed, historyJson };
}
const moduleText = (seed, encoded) => HEADER + 'export default ' + JSON.stringify({ ...seed, preparedHistory: encoded }) + ';\n';

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { seed, historyJson } = buildSeed();
  if (process.argv.includes('--check')) {
    // Compressed bytes may differ by zlib build, so the payload is compared after inflating.
    const existing = (await import(SEED_PATH.href)).default;
    const { preparedHistory, ...rest } = existing;
    if (JSON.stringify(rest) !== JSON.stringify(seed)) throw new Error('Trends seed is out of date.');
    if (inflateRawSync(Buffer.from(preparedHistory, 'base64')).toString('utf8') !== historyJson) throw new Error('Trends prepared history is out of date.');
    if (readFileSync(SEED_PATH, 'utf8') !== moduleText(seed, preparedHistory)) throw new Error('Trends seed module text differs.');
    console.log('Trends seed verified (' + Buffer.byteLength(readFileSync(SEED_PATH, 'utf8')) + ' bytes; prepared history ' + historyJson.length + ' bytes, sha256 ' + sha(historyJson) + ').');
  } else {
    const encoded = deflateRawSync(Buffer.from(historyJson), { level: 9 }).toString('base64');
    const text = moduleText(seed, encoded);
    writeFileSync(SEED_PATH, text);
    console.log('Trends seed generated (' + Buffer.byteLength(text) + ' bytes; prepared history ' + historyJson.length + ' bytes, sha256 ' + sha(historyJson) + ').');
  }
}
