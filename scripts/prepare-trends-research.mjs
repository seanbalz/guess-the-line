// Offline publication step; never imported by the browser or called in a request.
// node scripts/prepare-trends-research.mjs --season 2026 [--file .local/source.csv]
// Reproduction: --file <same bytes> --now <original generatedAt> --check
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { parseArgs } from 'node:util';
import { pathToFileURL } from 'node:url';
import { createResearchSnapshot, RESEARCH_PERIODS } from '../shared/trends-research-candidates.mjs';
import { TRENDS_SOURCE } from '../shared/trends.mjs';

const output = new URL('../cloud/trends-research-snapshot.mjs', import.meta.url);
const readJson = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const allowed = new Set(['version', 'generatedAt', 'season', 'source', 'candidates', 'targets']);
const redacted = ['spread', 'total', 'homeScore', 'awayScore', 'oddsHome', 'oddsAway',
  'oddsOver', 'oddsUnder', 'mlHome', 'mlAway', 'wind', 'temp', 'referee'];

/** A compressed, server-only module, containing public history and redacted
 * schedule context. No player or reviewed social-feed data belongs here. */
export function snapshotModule(snapshot) {
  if (!snapshot || Object.keys(snapshot).some(key => !allowed.has(key))) throw new Error('Unexpected snapshot field.');
  if (!Array.isArray(snapshot.candidates) || !Array.isArray(snapshot.targets)) throw new Error('Invalid snapshot.');
  for (const target of snapshot.targets) {
    if (target.played !== false || redacted.some(key => target[key] !== undefined && target[key] !== null)) {
      throw new Error('Upcoming snapshot context must be redacted.');
    }
  }
  const pack = value => gzipSync(Buffer.from(JSON.stringify(value)), { level: 9 }).toString('base64');
  const payload = pack({ ...snapshot, candidates: snapshot.candidates.map(({ periods, ...candidate }) => candidate) });
  const periodPayloads = Object.fromEntries(RESEARCH_PERIODS.map(period => [period,
    pack(snapshot.candidates.map(candidate => candidate.periods?.[period] ?? null))]));
  // Leave room for the rest of the Edge bundle within the documented 5 MB API
  // packaging limit. CLI bundles can be larger; neither is deployment evidence.
  if (payload.length + Object.values(periodPayloads).reduce((n, part) => n + part.length, 0) > 3_500_000) {
    throw new Error('Prepared snapshot exceeds the 3.5 MB artifact budget.');
  }
  const metadata = { version: snapshot.version, generatedAt: snapshot.generatedAt,
    season: snapshot.season, source: snapshot.source, candidates: snapshot.candidates.length,
    targets: snapshot.targets.length };
  return [
    '// Generated by scripts/prepare-trends-research.mjs. Server-only; public history, redacted schedule.',
    '// Data attribution: nflverse, CC BY 4.0. See metadata.source and docs/TRENDS_RESEARCH.md.',
    'export const snapshotMetadata = ' + JSON.stringify(metadata) + ';',
    'const payload = ' + JSON.stringify(payload) + ';',
    'const periodPayloads = ' + JSON.stringify(periodPayloads) + ';',
    'let base;',
    'const periods = new Map();',
    'async function decode(encoded) {',
    '    const bytes = Uint8Array.from(atob(encoded), c => c.charCodeAt(0));',
    "    const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));",
    '    return new Response(stream).json();',
    '}',
    "export default function loadResearchSnapshot(period = 'recent30') {",
    "  if (!Object.hasOwn(periodPayloads, period)) return Promise.reject(new Error('Unknown research period.'));",
    '  if (periods.has(period)) {',
    '    const cached = periods.get(period); periods.delete(period); periods.set(period, cached); return cached;',
    '  }',
    '  base ??= decode(payload);',
    '  const pending = Promise.all([base, decode(periodPayloads[period])]).then(([data, samples]) => ({',
    '    ...data, candidates: data.candidates.map((candidate, i) => ({ ...candidate, periods: { [period]: samples[i] } })),',
    '  }));',
    '  periods.set(period, pending);',
    '  while (periods.size > 2) periods.delete(periods.keys().next().value);',
    '  return pending;',
    '}',
    '',
  ].join('\n');
}

async function main() {
  const { values } = parseArgs({ options: {
    season: { type: 'string' }, file: { type: 'string' }, now: { type: 'string' },
    check: { type: 'boolean', default: false },
  } });
  const season = Number(values.season), now = values.now ?? new Date().toISOString();
  if (!Number.isSafeInteger(season) || season < 2002 || season > 2100 || !Number.isFinite(Date.parse(now))) {
    throw new Error('Pass --season and, if supplied, an ISO --now.');
  }
  let csv;
  if (values.file) csv = readFileSync(values.file, 'utf8');
  else {
    const response = await fetch(TRENDS_SOURCE.url, { signal: AbortSignal.timeout(20000) });
    if (!response.ok) throw new Error('Free history source unavailable: HTTP ' + response.status);
    csv = await response.text();
  }
  const snapshot = await createResearchSnapshot({ csv, now: new Date(now).toISOString(), season,
    registry: readJson('../shared/trends-registry.json'), venues: readJson('../shared/nfl-venues.json'),
    corrections: readJson('../shared/trends-corrections.json') });
  const source = snapshotModule(snapshot);
  if (values.check) {
    if (!existsSync(output) || readFileSync(output, 'utf8') !== source) throw new Error('Prepared snapshot differs; refresh and review before publication.');
  } else writeFileSync(output, source, 'utf8');
  console.log(JSON.stringify({ check: values.check, generatedAt: snapshot.generatedAt, season,
    latestCompleted: snapshot.source.latestCompleted, sourceSha256: snapshot.source.sha256,
    candidates: snapshot.candidates.length, targets: snapshot.targets.length,
    moduleBytes: Buffer.byteLength(source), uncompressedBytes: Buffer.byteLength(JSON.stringify(snapshot)) }));
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
