// Offline, reproducible calibration from the already-retained public NFL history.
// node scripts/prepare-nfl-gap-baseline.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { parseCsvRows, TRENDS_SOURCE, LINE_SOURCE } from '../shared/trends.mjs';

export const HISTORY_FILE = 'shared/trends/history-1999-2025.csv';
export const CORRECTIONS_FILE = 'shared/trends-corrections.json';
export const OUTPUT = 'shared/nfl-gap-baseline.mjs';
const root = new URL('../', import.meta.url);
const canonical = text => text.replace(/\r\n/g, '\n');
const sha = text => createHash('sha256').update(canonical(text)).digest('hex');
const number = value => typeof value === 'string' && value.trim() !== '' && Number.isFinite(Number(value)) ? Number(value) : null;
const round = value => Math.round(value * 1000000) / 1000000;

export function buildNflGapBaseline({ historyCsv, correctionsJson }) {
  const { rows } = parseCsvRows(historyCsv);
  const noContest = new Set(Object.keys(JSON.parse(correctionsJson).noContest ?? {}));
  const values = { spread: [], total: [] }, seen = new Set();
  const excluded = { noContest: 0, noFinal: 0, spreadLine: 0, totalLine: 0 };
  for (const row of rows) {
    const season = number(row.season);
    if (!Number.isInteger(season) || season < 2016 || season > 2025 || row.game_type !== 'REG') continue;
    if (!row.game_id || seen.has(row.game_id)) throw new Error('Missing or duplicate calibration game id.');
    seen.add(row.game_id);
    if (noContest.has(row.game_id)) { excluded.noContest++; continue; }
    const home = number(row.home_score), away = number(row.away_score);
    if (![home, away].every(v => Number.isInteger(v) && v >= 0)) { excluded.noFinal++; continue; }
    for (const market of ['spread', 'total']) {
      const line = number(row[market + '_line']);
      if (line === null || !Number.isInteger(line * 2) || (market === 'total' && line <= 0)) { excluded[market + 'Line']++; continue; }
      // nflverse spread_line is the expected HOME WINNING MARGIN (positive home
      // favorite), the opposite sign to GTL's home handicap. Never add it here.
      values[market].push(Math.abs((market === 'spread' ? home - away : home + away) - line));
    }
  }
  const markets = Object.fromEntries(Object.entries(values).map(([market, sample]) => {
    if (!sample.length) throw new Error('Empty ' + market + ' calibration.');
    sample.sort((a, b) => a - b);
    const counts = new Map();
    for (const gap of sample) counts.set(gap, (counts.get(gap) ?? 0) + 1);
    const quantile = p => sample[Math.ceil(sample.length * p) - 1];
    return [market, { n: sample.length, meanAbsoluteError: round(sample.reduce((a, b) => a + b, 0) / sample.length),
      median: quantile(0.5), upperQuartile: quantile(0.75), bins: [...counts] }];
  }));
  return { version: 'nfl-gap-2016-2025-v1', firstSeason: 2016, lastSeason: 2025, gameType: 'REG',
    source: { ...TRENDS_SOURCE, modified: '2016–2025 regular-season final-minus-line absolute errors, aggregated separately for Spread and Total.',
      lineSource: LINE_SOURCE, historyFile: HISTORY_FILE, historySha256: sha(historyCsv),
      correctionsFile: CORRECTIONS_FILE, correctionsSha256: sha(correctionsJson), hashEncoding: 'UTF-8, LF newlines' },
    excluded, markets };
}

export const serializeBaseline = baseline => '// Generated by scripts/prepare-nfl-gap-baseline.mjs; public historical aggregates only.\n'
  + '// Data: nflverse / Lee Sharpe, CC BY 4.0, modified. Provenance and limits are retained below.\n'
  + 'export default ' + JSON.stringify(baseline, null, 2) + ';\n';

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Only --check is supported.');
  const result = buildNflGapBaseline({ historyCsv: readFileSync(new URL(HISTORY_FILE, root), 'utf8'),
    correctionsJson: readFileSync(new URL(CORRECTIONS_FILE, root), 'utf8') });
  const output = serializeBaseline(result), file = new URL(OUTPUT, root);
  if (process.argv.includes('--check')) {
    if (canonical(readFileSync(file, 'utf8')) !== output) throw new Error('NFL gap baseline differs; regenerate and review.');
  } else writeFileSync(file, output);
  console.log(JSON.stringify({ output: OUTPUT, version: result.version, spread: result.markets.spread.n, total: result.markets.total.n }));
}
